# of the 64 graphs has a single entry point and can be traversed or deleted
# independently of the other 63.
roots = """
MATCH (f:NewSourceFramework {framework_id: 'CMMC_2_0'})
MATCH (n:NewSourceNode {framework_id: 'CMMC_2_0'})
WHERE NOT (:NewSourceNode {framework_id: 'CMMC_2_0'})-->(n)
MERGE (f)-[:HAS_ROOT]->(n);
"""

